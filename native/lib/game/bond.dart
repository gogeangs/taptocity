extension Bonds on Game {
  // ================= 인연 =================
  /// 인연 단계 0~5 (신뢰도 5를 넘어서 쌓인 경험치로 셈)
  int bondLv(int id) {
    final over = xpOf(id) - trustXp.last;
    if (over < 0) return 0;
    var l = 0;
    while (l < bondCum.length && over >= bondCum[l]) {
      l++;
    }
    return l;
  }

  /// 다음 인연 단계까지 (지금 쌓인 것, 필요한 것). 다 오르면 null
  (num, int)? bondNext(int id) {
    final l = bondLv(id);
    if (l >= bondCum.length) return null;
    final over = math.max(0, xpOf(id) - trustXp.last), pv = l == 0 ? 0 : bondCum[l - 1];
    return (over - pv, bondCum[l] - pv);
  }

  /// 지금까지 알린 인연 단계 (장면을 다시 볼 수 있는 단계)
  int bondSeen(int id) => math.min(bondLv(id), ((rec(id)?['bondN'] as num?) ?? bondLv(id)).toInt());

  bool bondGiftedToday(int id) => rec(id)?['bondDay'] == todayKey;

  /// 인연 장면 (제목, 대사)
  (String, List<Line>) bondScene(int id, int lv) {
    final l = lv.clamp(1, 5) - 1;
    final mine = bondScenes[id];
    if (mine != null) return mine[l];
    final (t, ls) = _bondGeneric[l][id % 2];
    final c = id < survivors.length ? _tnShort(id) : '누군가';
    String f(String s) => s
        .replaceAll('{ci}', jo(c, '이', '가'))
        .replaceAll('{cw}', jo(c, '과', '와'))
        .replaceAll('{c}', c)
        .replaceAll('{j}', id < survivors.length ? survivors[id].job : '');
    return (t, [for (final s in ls) Line('me', f(s))]);
  }

  /// 인연 장면 창 (다시 보기에도 쓴다)
  FxTalk bondTalk(int id, int lv) {
    final (t, ls) = bondScene(id, lv);
    return FxTalk(talkLines(ls), tag: '인연 Lv.$lv · ${survivors[id].name} · $t', replay: true);
  }

  /// 인연 선물: 신뢰도 5부터, 한 사람에게 하루(실제 날짜) 한 번. 다친 사람은 다 나을 때까지 받지 않는다
  bool bondGift(int id) {
    final r = rec(id);
    if (r == null || Game.trustLv(xpOf(id)) < 5) return false;
    final nm = survivors[id].name;
    if (((r['hurt'] as num?) ?? 0) > 0) {
      fx.add(FxNote(nm, '“${hurtGiftLine(id)}”\n다친 사람은 다 나을 때까지 인연이 깊어지지 않아요', ms: 4800));
      _changed();
      return false;
    }
    if (bondLv(id) >= bondCum.length) return false;
    if (r['bondDay'] == todayKey) {
      fx.add(FxToast('$nm에게는 오늘 이미 선물했어요 · 내일 또 줄 수 있어요'));
      _changed();
      return false;
    }
    if (!pay(bondGiftCost)) return false;
    r['bondDay'] = todayKey;
    r['xp'] = xpOf(id) + bondGiftXp;
    S.rest['giftN'] = num_('giftN') + 1;
    fx.add(FxToast('$nm 인연 +$bondGiftXp'));
    _changed();
    return true;
  }

  /// 인연 3단계의 고유 장비 (한 번만)
  void _bondGear(int id, {bool quiet = false}) {
    final t = bondGearOf[id], r = rec(id);
    if (t == null || r == null || r['bondG'] == 1 || gear[t] == null) return;
    r['bondG'] = 1;
    addGear(t);
    final G = gear[t]!;
    fx.add(FxNote('${survivors[id].name}의 고유 장비', '${G.n} · ${G.d}\n장비 가방에 들어왔어요', ms: quiet ? 5200 : 6000));
  }

  /// 매초: 인연이 한 단계 오른 사람이 있으면 (한 번에 한 사람, 창이 비어 있을 때) 장면을 연다
  void _tickBond() {
    if (tut != null || onb == 1) return;
    for (final id in svIds) {
      final r = rec(id)!, b = bondLv(id), seen = (r['bondN'] as num?)?.toInt();
      if (seen == null) {
        // 처음 보는 기록(옛 저장 포함)은 조용히 맞춘다. 이미 3단계를 넘었으면 고유 장비만 챙겨 준다
        r['bondN'] = b;
        if (b >= 3) _bondGear(id, quiet: true);
        continue;
      }
      if (b <= seen) continue;
      if (uiBusy) return;
      final n = seen + 1;
      r['bondN'] = n;
      sfx('chime');
      fx.add(FxToast('${survivors[id].name} 인연 Lv.$n! 새 이야기가 열렸어요'));
      final (t, ls) = bondScene(id, n);
      talk(ls, tag: '인연 Lv.$n · ${survivors[id].name} · $t');
      if (n >= 3) _bondGear(id);
      svNew = true;
      dirty = true;
      return;
    }
  }

  /// 인연 1 이상인 사람 수 (프로필 기록)
  int get bondN => svIds.where((id) => bondLv(id) >= 1).length;

  // ================= 그날 밤의 기록 조각 =================
  List<int> get fragsGot => [for (final v in (S.rest['frags'] as List? ?? const [])) if (v is num) v.toInt()];

  /// 이 조각이 지금 나올 수 있나: 재혁의 것은 고백을 들은 뒤에만
  bool _fragOk(int k) => frags[k].$1 != 9 || conf != null;

  /// 조각 하나를 줍는다 (없으면 -1): 함께 있는 사람의 것부터, 다 모았으면 다른 사람의 것, 겹치지 않게
  int fragDrop() {
    final got = fragsGot;
    var pool = [for (var k = 0; k < frags.length; k++) if (!got.contains(k) && _fragOk(k) && hasSv(frags[k].$1)) k];
    if (pool.isEmpty) pool = [for (var k = 0; k < frags.length; k++) if (!got.contains(k) && _fragOk(k)) k];
    if (pool.isEmpty) return -1;
    final pick = pool[rnd.nextInt(pool.length)];
    S.rest['frags'] = <Object?>[...got, pick];
    fx.add(fragTalk(pick, first: true));
    dirty = true;
    return pick;
  }

  /// 조각의 대사: 그 사람이 지금 무리에 없으면 '나'가 기억으로 옮긴다
  List<Line> fragLines(int k) {
    return [
      for (final l in frags[k].$3)
        if (l.who is int && (!hasSv(l.who as int) || isDead(l.who as int))) Line('me', '“${l.t}” — ${_tnShort(l.who as int)}') else l,
    ];
  }

  FxTalk fragTalk(int k, {bool first = false}) {
    final n = first ? fragsGot.length : fragsGot.indexOf(k) + 1;
    return FxTalk(fragLines(k), card: ('그날 밤의 기록 조각 · ${math.max(1, n)}/${frags.length}', frags[k].$2), scene: 'metro', replay: !first);
  }
}
